/**
 * Built-in idea types that are shipped with viben
 */
export const BUILTIN_IDEA_TYPES = [
  "code_improvements",
  "code_quality",
  "documentation_gaps",
  "performance_optimizations",
  "security_hardening",
  "ui_ux_improvements",
] as const;

/**
 * Type for built-in idea type names
 */
export type BuiltinIdeaTypeName = (typeof BUILTIN_IDEA_TYPES)[number];

/**
 * Effort levels for ideas
 * Represents the estimated work required to implement an idea
 */
export const EFFORT_LEVELS = [
  "trivial",
  "small",
  "medium",
  "large",
  "complex",
] as const;

/**
 * Type for effort level values
 */
export type EffortLevel = (typeof EFFORT_LEVELS)[number];

/**
 * Idea statuses in the lifecycle
 */
export const IDEA_STATUSES = ["draft", "promoted", "dismissed"] as const;

/**
 * Type for idea status values
 */
export type IdeaStatus = (typeof IDEA_STATUSES)[number];

/**
 * Mapping from effort level to default priority when promoting to task
 */
export const EFFORT_PRIORITY_MAP: Record<EffortLevel, string> = {
  trivial: "low",
  small: "low",
  medium: "medium",
  large: "high",
  complex: "high",
};

/**
 * Default maximum ideas per type
 */
export const DEFAULT_MAX_IDEAS = 5;

/**
 * Ideas output directory relative to .viben
 */
export const IDEAS_DIR = "ideas";

/**
 * Custom idea types directory
 */
export const CUSTOM_IDEA_TYPES_DIR = "docs/idea-types";

/**
 * Idea metadata file name
 */
export const IDEA_JSON_FILE = "idea.json";

/**
 * Idea markdown file prefix
 */
export const IDEA_FILE_PREFIX = "idea_";

// =============================================================================
// Idea Type (Prompt Template)
// =============================================================================

/**
 * Source of an idea type
 */
export type IdeaTypeSource = "builtin" | "custom";

/**
 * Represents an idea type (prompt template)
 *
 * Idea types define how ideas are generated. They can be:
 * - Built-in: shipped with viben in packages/core/src/prompts/idea-types/
 * - Custom: user-defined in docs/idea-types/
 */
export interface IdeaType {
  /** Type identifier (e.g., "code_improvements") */
  name: string;

  /** Human-readable description of this type */
  description: string;

  /** Default maximum ideas to generate for this type */
  maxIdeas?: number;

  /** Whether this is a built-in or custom type */
  source: IdeaTypeSource;

  /** Absolute path to the prompt template file */
  promptPath: string;
}

// =============================================================================
// Idea
