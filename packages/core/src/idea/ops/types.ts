/**
 * Check if a string is a valid effort level
 */
export function isValidEffortLevel(value: string): value is EffortLevel {
  return EFFORT_LEVELS.includes(value as EffortLevel);
}

/**
 * Check if a string is a valid idea status
 */
export function isValidIdeaStatus(value: string): value is IdeaStatus {
  return IDEA_STATUSES.includes(value as IdeaStatus);
}

/**
 * Check if a string is a built-in idea type
 */
export function isBuiltinIdeaType(value: string): value is BuiltinIdeaTypeName {
  return BUILTIN_IDEA_TYPES.includes(value as BuiltinIdeaTypeName);
}

/**
 * Get the default priority for an effort level
 */
export function getDefaultPriority(effort: EffortLevel): string {
  return EFFORT_PRIORITY_MAP[effort];
}

/**
 * Generate idea ID prefix from type name
 *
 * @param typeName - Idea type name
 * @returns Two-letter prefix (e.g., "ci" for code_improvements)
 */
export function getIdeaIdPrefix(typeName: string): string {
  // Take first letter of each word, max 2 letters
  const words = typeName.split("_");
  if (words.length >= 2) {
    return words[0][0] + words[1][0];
  }
  return typeName.slice(0, 2);
}

/**
 * Convert raw idea data from YAML to Idea interface
 */
export function parseRawIdea(raw: RawIdeaData): Idea {
  return {
    id: raw.id,
    type: raw.type,
    name: raw.name,
    title: raw.title,
    description: raw.description,
    rationale: raw.rationale,
    estimatedEffort: isValidEffortLevel(raw.estimated_effort)
      ? raw.estimated_effort
      : "medium",
    status: isValidIdeaStatus(raw.status) ? raw.status : "draft",
    promotedTo: raw.promoted_to || undefined,
    createdAt: raw.created_at,
    affectedFiles: raw.affected_files,
    existingPatterns: raw.existing_patterns,
    buildsUpon: raw.builds_upon,
    implementationApproach: raw.implementation_approach,
    category: raw.category,
    severity: raw.severity,
    targetAudience: raw.target_audience,
    relatedDocs: raw.related_docs,
    metrics: raw.metrics,
    uiComponents: raw.ui_components,
    userStories: raw.user_stories,
  };
}

/**
 * Convert raw session data from JSON to IdeaSession interface
 */
export function parseRawSession(raw: RawIdeaSession): IdeaSession {
  return {
    id: raw.id,
    types: raw.types,
    model: raw.model,
    summary: {
      totalIdeas: raw.summary.total_ideas,
      byType: raw.summary.by_type,
      byStatus: {
        draft: raw.summary.by_status.draft || 0,
        promoted: raw.summary.by_status.promoted || 0,
        dismissed: raw.summary.by_status.dismissed || 0,
      },
    },
    files: raw.files,
    generatedAt: raw.generated_at,
    updatedAt: raw.updated_at,
  };
}

/**
 * Generate a short UUID (8 characters)
 */
export function generateShortUuid(): string {
  return crypto.randomUUID().replace(/-/g, "").substring(0, 8);
}
