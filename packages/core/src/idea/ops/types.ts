/**
 * Summary statistics for an idea session
 */
export interface IdeaSessionSummary {
  /** Total number of ideas generated */
  totalIdeas: number;

  /** Count of ideas by type */
  byType: Record<string, number>;

  /** Count of ideas by status */
  byStatus: Record<IdeaStatus, number>;
}

/**
 * Raw session summary as stored in idea.json
 * Uses snake_case to match the file format
 */
export interface RawIdeaSessionSummary {
  total_ideas: number;
  by_type: Record<string, number>;
  by_status: Record<string, number>;
}

/**
 * Represents an idea session (idea.json metadata)
 *
 * Each idea generation creates a session directory with:
 * - idea.json: session metadata
 * - idea_*.md: ideas for each type
 */
export interface IdeaSession {
  /** Session identifier (e.g., "03-11-api-improvement") */
  id: string;

  /** Types that were generated in this session */
  types: string[];

  /** AI model used for generation */
  model: string;

  /** Summary statistics */
  summary: IdeaSessionSummary;

  /** Generated idea files */
  files?: string[];

  /** ISO timestamp when session was created */
  generatedAt: string;

  /** ISO timestamp when session was last updated */
  updatedAt: string;
}

/**
 * Raw session data as stored in idea.json
 * Uses snake_case to match the file format
 */
export interface RawIdeaSession {
  id: string;
  types: string[];
  model: string;
  summary: RawIdeaSessionSummary;
  files?: string[];
  generated_at: string;
  updated_at: string;
}

